    <h1>Le BTS SIO</h1>

    <div class="card">
        <h2>Présentation générale</h2>
        <p>Le BTS SIO (Services Informatiques aux Organisations) est un diplôme national de niveau Bac+2, préparé en deux ans après le baccalauréat. Il forme des techniciens supérieurs capables d'intervenir sur l'ensemble du cycle de vie des services informatiques d'une organisation : conception, déploiement, exploitation et maintenance.</p>
        <p>La formation se divise en deux options, orientées vers des métiers différents mais complémentaires :</p>
        <ul class="task-list">
            <li><strong>SLAM</strong> (Solutions Logicielles et Applications Métiers) : développement d'applications, gestion de bases de données, conception de logiciels.</li>
            <li><strong>SISR</strong> (Solutions d'Infrastructure, Systèmes et Réseaux) : administration de réseaux, serveurs, sécurité des systèmes d'information.</li>
        </ul>
    </div>

    <div class="card">
        <h2>Mon option : SLAM</h2>
        <p>J'ai choisi l'option SLAM, centrée sur le développement de solutions logicielles. Cette spécialisation couvre :</p>
        <ul class="task-list">
            <li>La conception et le développement d'applications (web, desktop, mobile)</li>
            <li>La modélisation et la gestion de bases de données relationnelles</li>
            <li>Les méthodes de gestion de projet (dont les méthodes agiles)</li>
            <li>Les tests, le débogage et la maintenance des applications</li>
            <li>La sécurisation des développements et des données</li>
        </ul>
    </div>

    <div class="card">
        <h2>Compétences visées</h2>
        <p>Au-delà du développement, la formation prépare aussi à des compétences transversales communes à toutes les options du BTS SIO :</p>
        <ul class="task-list">
            <li>Support et mise à disposition de services informatiques</li>
            <li>Cybersécurité des services informatiques</li>
            <li>Conduite de projet informatique</li>
        </ul>
    </div>
</section>